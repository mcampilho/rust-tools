pub fn def(lang: Lang) -> &'static Def {
    DEFS.iter().find(|d| d.lang == lang).unwrap_or(&DEFS[0])
}

impl Lang {
    pub fn name(self) -> &'static str {
        def(self).name
    }

    pub fn id(self) -> &'static str {
        match self {
            Lang::Plain => "plain",
            Lang::Rust => "rust",
            Lang::C => "c",
            Lang::Cpp => "cpp",
            Lang::CSharp => "csharp",
            Lang::Java => "java",
            Lang::JavaScript => "javascript",
            Lang::TypeScript => "typescript",
            Lang::Go => "go",
            Lang::Python => "python",
            Lang::Html => "html",
            Lang::Css => "css",
            Lang::Json => "json",
            Lang::Xml => "xml",
            Lang::Markdown => "markdown",
            Lang::Sql => "sql",
            Lang::Shell => "shell",
            Lang::PowerShell => "powershell",
            Lang::Batch => "batch",
            Lang::Ini => "ini",
            Lang::Toml => "toml",
            Lang::Yaml => "yaml",
            Lang::Properties => "properties",
            Lang::Diff => "diff",
        }
    }

    pub fn from_id(s: &str) -> Option<Lang> {
        DEFS.iter().map(|d| d.lang).find(|l| l.id() == s)
    }
}

/// Picks a language from the file name and, if that fails, the first line.
/// Unknown files are plain text.
pub fn detect(path: Option<&std::path::Path>, first_line: &str) -> Lang {
    if let Some(p) = path {
        let name = p.file_name().map(|n| n.to_string_lossy().into_owned()).unwrap_or_default();
        if let Some(d) = DEFS.iter().find(|d| d.filenames.iter().any(|f| f.eq_ignore_ascii_case(&name))) {
            return d.lang;
        }
        if let Some(ext) = p.extension().map(|e| e.to_string_lossy().to_ascii_lowercase()) {
            if let Some(d) = DEFS.iter().find(|d| d.exts.contains(&ext.as_str())) {
                return d.lang;
            }
        }
        if name.eq_ignore_ascii_case("makefile") || name.eq_ignore_ascii_case("dockerfile") {
            return Lang::Shell;
        }
    }
    let l = first_line.trim_start_matches('\u{feff}');
    if let Some(shebang) = l.strip_prefix("#!") {
        if shebang.contains("python") {
            return Lang::Python;
        }
        if shebang.contains("node") {
            return Lang::JavaScript;
        }
        if shebang.contains("pwsh") {
            return Lang::PowerShell;
        }
        if shebang.contains("sh") {
            return Lang::Shell;
        }
    }
    if l.starts_with("<?xml") {
        return Lang::Xml;
    }
    if l.to_ascii_lowercase().starts_with("<!doctype html") {
        return Lang::Html;
    }
    Lang::Plain
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::path::Path;

    #[test]
    fn detection() {
        assert_eq!(detect(Some(Path::new("a/b/main.rs")), ""), Lang::Rust);
        assert_eq!(detect(Some(Path::new("X.HPP")), ""), Lang::Cpp);
        assert_eq!(detect(Some(Path::new("app.csproj")), ""), Lang::Xml);
        assert_eq!(detect(Some(Path::new("Cargo.lock")), ""), Lang::Toml);
        assert_eq!(detect(Some(Path::new("notes.unknownext")), "hello"), Lang::Plain);
        assert_eq!(detect(Some(Path::new("script")), "#!/usr/bin/env python3"), Lang::Python);
        assert_eq!(detect(None, "<?xml version=\"1.0\"?>"), Lang::Xml);
        assert_eq!(detect(None, "plain words"), Lang::Plain);
        for d in DEFS {
            assert_eq!(Lang::from_id(d.lang.id()), Some(d.lang));
        }
    }
}
