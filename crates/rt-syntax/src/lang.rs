//! Language definitions: detection by file name, comment syntax, keywords.

#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Lang {
    Plain,
    Rust,
    C,
    Cpp,
    CSharp,
    Java,
    JavaScript,
    TypeScript,
    Go,
    Python,
    Html,
    Css,
    Json,
    Xml,
    Markdown,
    Sql,
    Shell,
    PowerShell,
    Batch,
    Ini,
    Toml,
    Yaml,
    Properties,
    Diff,
}

/// Lexing family: which tokenizer handles the language.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Family {
    Plain,
    Code,
    Markup,
    Markdown,
    Ini,
    Diff,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum FoldStyle {
    None,
    Braces,
    Indent,
    Tags,
    Headings,
}

/// A string delimiter.
#[derive(Clone, Copy, Debug)]
pub struct Quote {
    pub open: &'static str,
    pub close: &'static str,
    pub escape: bool,
    pub multiline: bool,
}

const fn q(open: &'static str, close: &'static str, escape: bool, multiline: bool) -> Quote {
    Quote {
        open,
        close,
        escape,
        multiline,
    }
}

pub struct Def {
    pub lang: Lang,
    pub name: &'static str,
    pub family: Family,
    pub exts: &'static [&'static str],
    pub filenames: &'static [&'static str],
    pub line_comments: &'static [&'static str],
    pub block_comment: Option<(&'static str, &'static str)>,
    pub nested_comments: bool,
    pub quotes: &'static [Quote],
    pub keywords: &'static [&'static str],
    pub types: &'static [&'static str],
    pub constants: &'static [&'static str],
    pub case_insensitive: bool,
    /// `#` at line start starts a preprocessor line (C, C#).
    pub preproc: bool,
    /// Prefix for variables (`$x`).
    pub var_prefix: Option<char>,
    /// Extra identifier characters.
    pub ident_extra: &'static str,
    pub fold: FoldStyle,
    /// Text endings (after trimming) that increase indentation on Enter.
    pub indent_after: &'static [&'static str],
}

impl Def {
    pub fn comment_token(&self) -> Option<&'static str> {
        self.line_comments.first().copied()
    }
}

