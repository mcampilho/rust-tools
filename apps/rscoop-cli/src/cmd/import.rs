//! `import <scoopfile.json>` (`libexec\scoop-import.ps1`): the settings, the
//! buckets and the apps of an `export`, in that order, each app as its own
//! `install` (a failure stops that app, not the others) and then `hold` if
//! it was held. A file from a web address, and `use_isolated_path` among
//! the settings (which moves `PATH` entries), are Scoop's.

use super::{bucket, delegate, install, maintain, update, Ctx};
use rt_scoop::json::{self, Json};
use rt_scoop::manifest::Arch;
use rt_scoop::resolve;

/// `set_config`: the texts "true" and "false" become booleans.
fn setting_value(value: &Json) -> Json {
    match value {
        Json::Str(s) if s.eq_ignore_ascii_case("true") => Json::Bool(true),
        Json::Str(s) if s.eq_ignore_ascii_case("false") => Json::Bool(false),
        other => other.clone(),
    }
}

/// A value as PowerShell writes it in a string.
fn shown(value: &Json) -> String {
    match value {
        Json::Bool(true) => "True".into(),
        Json::Bool(false) => "False".into(),
        Json::Str(s) => s.clone(),
        Json::Null => String::new(),
        other => json::pretty(other).split_whitespace().collect::<Vec<_>>().join(" "),
    }
}

pub fn run(ctx: &mut Ctx, args: &[String]) -> i32 {
    let Some(file) = args.first() else { return ctx.fail("error.missing", &[("what", "<scoopfile>")]) };
    let to_scoop = |ctx: &mut Ctx| {
        let mut line = vec!["import".to_string()];
        line.extend(args.iter().cloned());
        delegate::run(ctx, &line, ctx.root_given)
    };
    if resolve::is_remote(file) {
        return to_scoop(ctx);
    }
    let Some(import @ Json::Obj(_)) = json::read(std::path::Path::new(file)) else {
        return ctx.fail("import.invalid", &[]);
    };
    let settings = match import.get("config") {
        Json::Obj(members) => members.clone(),
        _ => Vec::new(),
    };
    if settings.iter().any(|(k, _)| k.eq_ignore_ascii_case("use_isolated_path")) {
        return to_scoop(ctx);
    }
    for (name, value) in &settings {
        let value = setting_value(value);
        if let Err(code) = update::set_setting(ctx, &name.to_lowercase(), Some(value.clone())) {
            return code;
        }
        let line = ctx.t.fill("import.set", &[("name", name), ("value", &shown(&value))]);
        ctx.say(line);
    }

    let mut names: Vec<String> = Vec::new();
    for b in import.get("buckets").items() {
        let name = b.get("Name").str().to_string();
        let source = b.get("Source").str().to_string();
        let mut line = vec![name.clone()];
        if !source.is_empty() {
            line.push(source);
        }
        // Already there, or failed: said, and the import goes on.
        bucket::add(ctx, &line);
        names.push(name);
    }

    let default = ctx.arch();
    for item in import.get("apps").items() {
        let name = item.get("Name").str().to_string();
        let source = item.get("Source").str();
        let info: Vec<&str> = item.get("Info").str().split(", ").collect();
        let mut install_args = Vec::new();
        let mut hold_args = Vec::new();
        if info.contains(&"Global install") {
            install_args.push("--global".to_string());
            hold_args.push("--global".to_string());
        }
        for arch in [Arch::X64, Arch::X86, Arch::Arm64] {
            if info.contains(&arch.name()) {
                if arch != default {
                    install_args.extend(["--arch".to_string(), arch.name().to_string()]);
                }
                break;
            }
        }
        let app = if names.iter().any(|n| n == source) {
            format!("{source}/{name}")
        } else if source == "<auto-generated>" {
            format!("{name}@{}", item.get("Version").str())
        } else {
            source.to_string()
        };
        let mut line = vec![app];
        line.extend(install_args);
        install::run(ctx, &line);
        if info.contains(&"Held package") {
            let mut line = vec![name];
            line.extend(hold_args);
            maintain::hold(ctx, &line, true);
        }
    }
    0
}
