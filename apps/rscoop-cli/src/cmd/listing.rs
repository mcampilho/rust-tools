//! `list`, `search` and `export`.

use super::{state, table, Ctx};
use crate::checks::parallel;
use crate::sys::local_time;
use regex_lite::{Regex, RegexBuilder};
use rt_scoop::apps;
use rt_scoop::buckets;
use rt_scoop::install::Scoop;
use rt_scoop::json::{self, object, string, Json};
use rt_scoop::manifest::{Arch, Manifest};
use std::path::Path;

/// One installed app, as `scoop list` shows it.
#[derive(Debug)]
pub struct Row {
    pub name: String,
    pub version: String,
    pub source: String,
    pub updated: Option<std::time::SystemTime>,
    /// In English, as `scoop export` writes it and `scoop import` reads it.
    pub info: Vec<String>,
}

/// A regular expression that ignores case, as PowerShell's `-match`.
pub fn query(ctx: &mut Ctx, text: &str) -> Result<Regex, i32> {
    RegexBuilder::new(text).case_insensitive(true).build().map_err(|e| {
        let why = e.to_string();
        ctx.fail("error.regex", &[("why", &why)])
    })
}

fn row(scoop: &Scoop, default_arch: Arch, name: &str, global: bool) -> Row {
    let version = apps::current_version(scoop, name, global).unwrap_or_default();
    let Some(info) = apps::install_info(scoop, name, &version, global) else {
        let updated = std::fs::metadata(scoop.app(name, global)).and_then(|m| m.modified()).ok();
        return Row { name: name.into(), version, source: String::new(), updated, info: vec!["Install failed".into()] };
    };
    let updated = apps::info_file(scoop, name, &version, global).and_then(|p| std::fs::metadata(p).ok()).and_then(|m| m.modified().ok());
    let mut notes = Vec::new();
    if buckets::deprecated(scoop, name, info.bucket.as_deref().unwrap_or("")).is_some() {
        notes.push("Deprecated package".to_string());
    }
    if global {
        notes.push("Global install".to_string());
    }
    if info.hold {
        notes.push("Held package".to_string());
    }
    if !info.architecture.is_empty() && info.architecture != default_arch.name() {
        notes.push(info.architecture.clone());
    }
    let source = match (info.bucket, info.url) {
        (Some(bucket), _) => bucket,
        (None, Some(url)) if Path::new(&url) == scoop.root.join("workspace").join(format!("{name}.json")) => "<auto-generated>".into(),
        (None, url) => url.unwrap_or_default(),
    };
    Row { name: name.into(), version, source, updated, info: notes }
}

/// The installed apps matching `filter`: the user's, then the global ones.
pub fn installed(ctx: &Ctx, filter: Option<&Regex>) -> Vec<Row> {
    let mut names = Vec::new();
    for global in [false, true] {
        for name in apps::installed_names(&ctx.scoop, global) {
            if filter.is_none_or(|f| f.is_match(&name)) {
                names.push((name, global));
            }
        }
    }
    let (scoop, arch) = (&ctx.scoop, ctx.arch());
    parallel(&names, |(name, global)| row(scoop, arch, name, *global))
}

fn row_json(r: &Row) -> Json {
    object([
        ("Name", string(r.name.clone())),
        ("Version", string(r.version.clone())),
        ("Source", string(r.source.clone())),
        ("Updated", r.updated.map_or(Json::Null, |t| string(local_time(t).iso))),
        ("Info", string(r.info.join(", "))),
    ])
}

fn info_shown(ctx: &Ctx, info: &str) -> String {
    match info {
        "Install failed" => ctx.t.get("info.failed").into(),
        "Deprecated package" => ctx.t.get("info.deprecated_package").into(),
        "Global install" => ctx.t.get("info.global").into(),
        "Held package" => ctx.t.get("info.held").into(),
        other => other.into(),
    }
}

pub fn list(ctx: &mut Ctx, args: &[String]) -> i32 {
    let filter = match args.first() {
        Some(q) => match query(ctx, q) {
            Ok(r) => Some(r),
            Err(code) => return code,
        },
        None => None,
    };
    let rows = installed(ctx, filter.as_ref());
    if ctx.json {
        ctx.print_json(&Json::Arr(rows.iter().map(row_json).collect()));
        return 0;
    }
    if rows.is_empty() && filter.is_none() {
        let root = ctx.scoop.root.display().to_string();
        return ctx.fail("list.none", &[("root", &root)]);
    }
    let head = match args.first() {
        Some(q) => ctx.t.fill("list.matching", &[("query", q), ("root", &ctx.scoop.root.display().to_string())]),
        None => ctx.t.fill("list.installed", &[("root", &ctx.scoop.root.display().to_string())]),
    };
    let cells: Vec<Vec<String>> = rows
        .iter()
        .map(|r| {
            let info: Vec<String> = r.info.iter().map(|i| info_shown(ctx, i)).collect();
            let updated = r.updated.map(|t| local_time(t).short).unwrap_or_default();
            vec![r.name.clone(), r.version.clone(), r.source.clone(), updated, info.join(", ")]
        })
        .collect();
    ctx.say(head);
    ctx.say("");
    for line in table::lines(&["Name", "Version", "Source", "Updated", "Info"], &cells) {
        ctx.say(line);
    }
    0
}

/// A manifest found by `search`.
struct Found {
    name: String,
    version: String,
    source: String,
    binaries: String,
}

/// `bin_match_json`: the names of the programs that match. As in Scoop, only
/// the general `bin` is looked at.
fn bin_match(manifest: &Manifest, query: &Regex) -> Vec<String> {
    let leaf = |p: &str| p.rsplit(['\\', '/']).next().unwrap_or(p).to_string();
    let bins = Manifest(object([("bin", manifest.get("bin").clone())])).bins(Arch::X64);
    let mut found = Vec::new();
    for bin in bins {
        let file = leaf(&bin.target);
        let stem = file.rsplit_once('.').map_or(file.as_str(), |(s, _)| s);
        if query.is_match(stem) {
            found.push(file);
        } else if let Some(alias) = bin.alias.filter(|a| query.is_match(a)) {
            found.push(alias);
        }
    }
    found.dedup();
    found
}

pub fn search(ctx: &mut Ctx, args: &[String]) -> i32 {
    let text = args.first().cloned().unwrap_or_default();
    let regex = match query(ctx, &text) {
        Ok(r) => r,
        Err(code) => return code,
    };
    let mut files = Vec::new();
    for bucket in buckets::local(&ctx.scoop) {
        for (name, path) in buckets::manifests_under(&buckets::manifest_dir(&ctx.scoop, &bucket)) {
            files.push((bucket.clone(), name, path));
        }
    }
    let found: Vec<Found> = parallel(&files, |(bucket, name, path)| {
        let by_name = regex.is_match(name);
        let content = json::read_text(path)?;
        if !by_name && !regex.is_match(&content) {
            return None;
        }
        let manifest = Manifest(json::parse(&content)?);
        let binaries = if by_name { Vec::new() } else { bin_match(&manifest, &regex) };
        (by_name || !binaries.is_empty()).then(|| Found {
            name: name.clone(),
            version: manifest.version().to_string(),
            source: bucket.clone(),
            binaries: binaries.join(" | "),
        })
    })
    .into_iter()
    .flatten()
    .collect();
    if ctx.json {
        let rows = found
            .iter()
            .map(|f| {
                object([
                    ("Name", string(f.name.clone())),
                    ("Version", string(f.version.clone())),
                    ("Source", string(f.source.clone())),
                    ("Binaries", string(f.binaries.clone())),
                ])
            })
            .collect();
        ctx.print_json(&Json::Arr(rows));
        return i32::from(found.is_empty());
    }
    if found.is_empty() {
        // Scoop would now ask GitHub about the known buckets not added.
        return ctx.fail("search.none", &[("query", &text)]);
    }
    let cells: Vec<Vec<String>> = found.into_iter().map(|f| vec![f.name, f.version, f.source, f.binaries]).collect();
    for line in table::lines(&["Name", "Version", "Source", "Binaries"], &cells) {
        ctx.say(line);
    }
    0
}

pub fn export(ctx: &mut Ctx, args: &[String]) -> i32 {
    let mut members = Vec::new();
    if args.iter().any(|a| a == "-c" || a == "--config") {
        let private = ["last_update", "root_path", "global_path", "cache_path", "alias"];
        let config = match &ctx.scoop.config {
            Json::Obj(m) => m.iter().filter(|(k, _)| !private.iter().any(|p| p.eq_ignore_ascii_case(k))).cloned().collect(),
            _ => Vec::new(),
        };
        members.push(("config".to_string(), Json::Obj(config)));
    }
    members.push(("buckets".to_string(), Json::Arr(state::buckets_found(ctx).iter().map(state::bucket_json).collect())));
    members.push(("apps".to_string(), Json::Arr(installed(ctx, None).iter().map(row_json).collect())));
    ctx.print_json(&Json::Obj(members));
    0
}
