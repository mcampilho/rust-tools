/// A name as lower-case words separated by single spaces, with a space at
/// each end, so whole words can be looked for with `contains`.
fn words(name: &str) -> String {
    let lower = name.to_lowercase();
    let cleaned: String = lower.chars().map(|c| if c.is_alphanumeric() || matches!(c, '+' | '-' | '.') { c } else { ' ' }).collect();
    format!(" {} ", cleaned.split_whitespace().collect::<Vec<_>>().join(" "))
}

/// The category of the first of `names` (the shortcut's, then the program
/// file's) that has a known word.
pub fn guess(names: &[&str]) -> Category {
    for name in names {
        let w = words(name);
        for (category, known) in KNOWN {
            if known.iter().any(|k| w.contains(&format!(" {k} "))) {
                return *category;
            }
        }
    }
    Category::Other
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn known_programs_find_their_category() {
        for (name, want) in [
            ("Firefox", Category::Internet),
            ("Google Chrome", Category::Internet),
            ("Android Studio", Category::Development),
            ("Visual Studio Code", Category::Development),
            ("Audacity", Category::Multimedia),
            ("Blender", Category::Graphics),
            ("Calibre E-Book Viewer", Category::Office),
            ("Excel", Category::Office),
            ("Steam", Category::Games),
            ("IObit Uninstaller", Category::System),
            ("Bitwarden", Category::Security),
            ("Double Commander", Category::Utilities),
            ("Celestia", Category::Other),
        ] {
            assert_eq!(guess(&[name]), want, "{name}");
        }
        // A word inside another is not that word.
        assert_eq!(guess(&["Gogland"]), Category::Other);
        // The file name helps when the shortcut's name says nothing.
        assert_eq!(guess(&["My editor", "notepad++"]), Category::Development);
    }
}
